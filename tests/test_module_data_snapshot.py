def _drift(builder, mutate) -> list[str]:
    """Run the comparison --check runs, against a snapshot mutated one way."""

    committed = json.loads(MODULES_SNAPSHOT.read_text(encoding="utf-8"))
    regenerated = copy.deepcopy(committed)
    mutate(regenerated)
    return builder.diff_summary(
        "modules.json", builder.serialize(regenerated), builder.serialize(committed)
    )


def test_an_unchanged_snapshot_reports_no_drift(builder):
    assert _drift(builder, lambda snapshot: None) == []


def test_a_changed_version_fails_the_check(builder):
    def mutate(snapshot):
        snapshot["modules"][0]["version"] = "99.0.0"

    lines = _drift(builder, mutate)
    assert lines, "a changed version did not register as drift"
    assert any("99.0.0" in line for line in lines)


def test_a_removed_module_fails_the_check(builder):
    def mutate(snapshot):
        removed = snapshot["modules"].pop()
        snapshot["module_count"] = len(snapshot["modules"])
        snapshot["removed"] = removed["name"]

    lines = _drift(builder, mutate)
    assert lines, "a removed module did not register as drift"


def test_an_added_field_fails_the_check(builder):
    def mutate(snapshot):
        snapshot["modules"][0]["boards_tested"] = ["apollo510_evb"]

    lines = _drift(builder, mutate)
    assert lines, "an added field did not register as drift"
    assert any("boards_tested" in line for line in lines)


def test_a_changed_board_fails_the_check(builder):
    committed = json.loads(BOARDS_SNAPSHOT.read_text(encoding="utf-8"))
    mutated = copy.deepcopy(committed)
    mutated["boards"][0]["tier"] = "production"
    lines = builder.diff_summary(
        "boards.json", builder.serialize(mutated), builder.serialize(committed)
    )
    assert lines, "a changed board tier did not register as drift"
    assert any("production" in line for line in lines)


def test_the_check_reports_a_missing_snapshot(builder, tmp_path, capsys):
    exit_code = builder.check(
        tmp_path / "modules.json",
        tmp_path / "boards.json",
        workspace=tmp_path / "workspace",
        offline=True,
    )
    assert exit_code == 1
    assert "does not exist" in capsys.readouterr().err


def test_an_unreadable_manifest_is_reported_rather_than_compared(builder, modules):
    """A private project answers a credential-less run with an access error.

    That is not drift, so the check carries the committed manifest fields over
    and names the module instead of failing on it.
    """

    regenerated = copy.deepcopy(modules)
    target = next(entry for entry in regenerated["modules"] if entry["manifest_source"] == "git")
    target["manifest_source"] = "unavailable"
    target["manifest_error"] = "repository not found"
    for field in builder.MANIFEST_FIELDS:
        target[field] = None

    reconciled, skipped = builder.reconcile_unavailable(regenerated, modules)
    assert skipped == [target["name"]]
    assert builder.serialize(reconciled) == builder.serialize(modules)


def test_a_module_missing_from_a_reachable_project_is_still_drift(builder, modules):
    """Reconciling an unreadable manifest must not paper over a real change."""

    regenerated = copy.deepcopy(modules)
    regenerated["modules"][0]["version"] = "99.0.0"
    reconciled, skipped = builder.reconcile_unavailable(regenerated, modules)
    assert skipped == []
    assert builder.diff_summary(
        "modules.json", builder.serialize(reconciled), builder.serialize(modules)
    )


def test_manifest_paths_resolve_the_way_the_resolver_resolves_them(builder, registry_lock):
    """The generator strips a project's own path prefix, as the resolver does."""

    assert builder.manifest_relpath("modules/helia-rt/nsx-module.yaml", "modules/helia-rt") == Path(
        "nsx-module.yaml"
    )
    assert builder.manifest_relpath(
        "modules/nsx-ambiqsuite/nsx-module.yaml", "modules/nsx-ambiq-sdk"
    ) == Path("modules/nsx-ambiqsuite/nsx-module.yaml")
    assert builder.manifest_relpath("modules/x/nsx-module.yaml", None) == Path(
        "modules/x/nsx-module.yaml"
    )


def test_the_offline_build_reads_the_manifests_this_repository_ships(builder, tmp_path, modules):
    """Without the network the packaged manifests still resolve, and only those."""

    offline = builder.build_modules(workspace=tmp_path, offline=True)
    committed = {entry["name"]: entry for entry in modules["modules"]}
    packaged = [entry for entry in offline["modules"] if entry["manifest_source"] == "packaged"]
    assert packaged, "no module resolves from packaged content"
    for entry in packaged:
        assert entry == committed[entry["name"]], entry["name"]
