def test_every_registry_module_is_in_the_snapshot(modules, registry_lock):
    assert {entry["name"] for entry in modules["modules"]} == set(registry_lock["modules"])
    assert modules["module_count"] == len(modules["modules"])


def test_the_snapshot_agrees_with_the_discovery_api(modules):
    """The registry fields come from the API, so they have to match it."""

    records = {record.name: record for record in list_modules(registry_only=True)}
    for entry in modules["modules"]:
        record = records[entry["name"]]
        assert entry["project"] == record.project
        assert entry["revision"] == record.revision
        assert entry["metadata_path"] == record.metadata


def test_every_module_carries_every_field(modules):
    for entry in modules["modules"]:
        assert set(entry) == MODULE_KEYS, entry["name"]
        assert entry["slug"] == entry["name"]
        assert isinstance(entry["capabilities"], list)
        assert isinstance(entry["use_cases"], list)
        assert isinstance(entry["anti_use_cases"], list)
        assert isinstance(entry["agent_keywords"], list)
        assert set(entry["depends"]) == {"required", "optional"}
        assert set(entry["compatibility"]) == {"boards", "socs", "toolchains"}


def test_every_module_declares_a_known_type(modules):
    for entry in modules["modules"]:
        if entry["manifest_source"] == "unavailable":
            continue
        assert entry["type"] in MODULE_TYPES, entry["name"]
        assert entry["version"], entry["name"]
        assert entry["compatibility"]["boards"], entry["name"]
        assert entry["compatibility"]["socs"], entry["name"]
        assert entry["compatibility"]["toolchains"], entry["name"]


def test_every_repo_url_is_the_registry_project_url(modules, registry_lock):
    for entry in modules["modules"]:
        project = registry_lock["projects"][entry["project"]]
        assert entry["repo_url"] == project["url"].removesuffix(".git")
        assert entry["source_url"] == f"{entry['repo_url']}/tree/{entry['revision']}"


def test_dependencies_name_modules_that_exist(modules):
    """Every dependency should be a module the catalog can link to.

    Four are not, so the catalog renders them as plain names rather than links.
    They are pinned here rather than ignored: the set is a fact about the
    registry, and a fifth one appearing should be somebody's decision, not a
    silent change to what the catalog links.
    """

    dangling_by_design = {
        ("nsx-ethos-u-driver", "nsx-harness"),
        ("nsx-power", "nsx-timer"),
        ("nsx-uart", "nsx-interrupt"),
        ("nsx-usb", "nsx-timer"),
    }
    known = {entry["name"] for entry in modules["modules"]}
    dangling = {
        (entry["name"], name)
        for entry in modules["modules"]
        for name in entry["depends"]["required"] + entry["depends"]["optional"]
        if name not in known
    }
    assert dangling == dangling_by_design


def test_the_snapshot_records_where_each_manifest_came_from(modules):
    sources = {entry["manifest_source"] for entry in modules["modules"]}
    assert sources <= {"packaged", "git", "unavailable"}
    for entry in modules["modules"]:
        if entry["manifest_source"] == "unavailable":
            assert entry["manifest_error"], entry["name"]
        else:
            assert entry["manifest_error"] is None, entry["name"]


def test_the_board_matrix_matches_every_board_descriptor(boards):
    descriptors = load_board_descriptors()
    assert [board["name"] for board in boards["boards"]] == list(BOARDS)
    assert boards["board_count"] == len(BOARDS)
    for index, board in enumerate(boards["boards"]):
        descriptor = descriptors[board["name"]]
        assert set(board) == BOARD_KEYS, board["name"]
        assert board["order"] == index
        assert board["soc"] == descriptor.soc
        assert board["tier"] == descriptor.tier
        assert board["sdk_provider"] == descriptor.sdk_provider
        assert board["registered"] == descriptor.registered
        assert board["toolchains"] == list(descriptor.toolchains)
        assert board["cpu"] == {
            "core": descriptor.cpu.core,
            "float_abi": descriptor.cpu.float_abi,
            "abi": descriptor.cpu.abi,
        }


def test_the_soc_families_match_the_registry_lock(boards, registry_lock):
    assert set(boards["soc_families"]) == set(registry_lock["soc_families"])
    for soc, family in boards["soc_families"].items():
        declared = registry_lock["soc_families"][soc]
        assert family["provider"] == declared.get("provider")
        assert family["project"] == declared.get("project")
        assert family["revision"] == declared.get("revision")
        assert family["modules"] == list(declared.get("modules") or [])


def test_every_board_soc_has_a_family(boards):
    for board in boards["boards"]:
        assert board["soc_family"] == board["soc"], board["name"]


def test_the_snapshot_makes_no_hardware_claim(modules):
    """Compatibility is declared by a manifest, so no manifest may say more."""

    forbidden = ("validated on", "tested on", "verified on", "hardware validated")
    for entry in modules["modules"]:
        prose = " ".join([
            entry["summary"] or "",
            *entry["use_cases"],
            *entry["anti_use_cases"],
        ]).lower()
        for phrase in forbidden:
            assert phrase not in prose, f"{entry['name']} claims {phrase!r}"


