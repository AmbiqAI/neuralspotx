"""Prove the committed module and board snapshots still describe this tree.

``astro-site/src/data/modules.json`` and ``boards.json`` are generated by
``scripts/docs/build_module_data.py`` and committed, because the module
manifests live in other repositories and the site build is not allowed to
fetch them. A committed artifact is only worth having if something fails when
it drifts, so this module checks two things.

The snapshot is checked against the tree it claims to describe: every module in
the registry lock is in it, every board descriptor the package ships is in it,
in the package's own order, and every value is the shape the site renders.
That part needs no network.

The drift check itself is checked by mutation. ``--check`` regenerates the
snapshot and compares it with the committed one, so the comparison is the thing
that has to be trusted; each test here feeds it a snapshot that differs in one
way a real change would and asserts that it says so.
"""

from __future__ import annotations

import copy
import importlib
import json
import sys
from pathlib import Path
from typing import Any

import pytest
import yaml

from neuralspotx import list_modules
from neuralspotx.board_descriptors import load_board_descriptors
from neuralspotx.constants import BOARDS
from neuralspotx.metadata import ModuleType

REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = REPO_ROOT / "scripts" / "docs"
SITE = REPO_ROOT / "astro-site"
MODULES_SNAPSHOT = SITE / "src" / "data" / "modules.json"
BOARDS_SNAPSHOT = SITE / "src" / "data" / "boards.json"
REGISTRY_LOCK = REPO_ROOT / "src" / "neuralspotx" / "data" / "registry.lock.yaml"

MODULE_TYPES = {member.value for member in ModuleType}

# Every key the site's generator reads off a module. A field added to the
# snapshot without a renderer is harmless; a field removed from under one is
# not, so the set is exact rather than a subset.
MODULE_KEYS = {
    "name",
    "slug",
    "project",
    "revision",
    "metadata_path",
    "repo_url",
    "source_url",
    "manifest_source",
    "manifest_error",
    "type",
    "category",
    "provider",
    "version",
    "summary",
    "capabilities",
    "use_cases",
    "anti_use_cases",
    "agent_keywords",
    "provides",
    "depends",
    "compatibility",
    "constraints",
    "example_refs",
    "integrations",
}

BOARD_KEYS = {
    "order",
    "name",
    "soc",
    "soc_family",
    "tier",
    "sdk_provider",
    "sdk_provider_module",
    "cpu",
    "toolchains",
    "registered",
}


def _builder():
    """Import scripts/docs/build_module_data.py without packaging scripts/."""

    if str(SCRIPTS) not in sys.path:
        sys.path.insert(0, str(SCRIPTS))
    return importlib.import_module("build_module_data")


@pytest.fixture(scope="module")
def builder():
    return _builder()


@pytest.fixture(scope="module")
def modules() -> dict[str, Any]:
    return json.loads(MODULES_SNAPSHOT.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def boards() -> dict[str, Any]:
    return json.loads(BOARDS_SNAPSHOT.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def registry_lock() -> dict[str, Any]:
    return yaml.safe_load(REGISTRY_LOCK.read_text(encoding="utf-8"))


